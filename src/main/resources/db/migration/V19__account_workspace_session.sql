-- 只新增身份基础；旧 owner/project 不自动认领给任何注册账号。
CREATE TABLE dt_account (
    id UUID PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(512) NOT NULL,
    display_name VARCHAR(100) NOT NULL CHECK (length(btrim(display_name)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (email = lower(btrim(email)) AND length(email) > 3)
);

CREATE TABLE dt_workspace (
    id UUID PRIMARY KEY,
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('PERSONAL', 'TEAM')),
    name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0),
    personal_user_id UUID UNIQUE REFERENCES dt_account(id),
    owner_id VARCHAR(128) NOT NULL,
    project_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (owner_id, project_id),
    CHECK ((kind = 'PERSONAL') = (personal_user_id IS NOT NULL))
);

CREATE TABLE dt_workspace_member (
    workspace_id UUID NOT NULL REFERENCES dt_workspace(id),
    user_id UUID NOT NULL REFERENCES dt_account(id),
    role VARCHAR(16) NOT NULL CHECK (role IN ('ADMIN', 'COLLABORATOR', 'VIEWER')),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (workspace_id, user_id)
);
CREATE INDEX dt_workspace_member_user ON dt_workspace_member(user_id, workspace_id);

-- Spring Session JDBC PostgreSQL schema；由 Flyway 管理，不启用启动自动建表。
CREATE TABLE SPRING_SESSION (
    PRIMARY_ID CHAR(36) NOT NULL PRIMARY KEY,
    SESSION_ID CHAR(36) NOT NULL,
    CREATION_TIME BIGINT NOT NULL,
    LAST_ACCESS_TIME BIGINT NOT NULL,
    MAX_INACTIVE_INTERVAL INT NOT NULL,
    EXPIRY_TIME BIGINT NOT NULL,
    PRINCIPAL_NAME VARCHAR(100)
);
CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION(SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION(EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION(PRINCIPAL_NAME);
CREATE TABLE SPRING_SESSION_ATTRIBUTES (
    SESSION_PRIMARY_ID CHAR(36) NOT NULL REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE,
    ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
    ATTRIBUTE_BYTES BYTEA NOT NULL,
    PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME)
);
